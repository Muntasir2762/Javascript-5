
function summation(data1, data2){
    let number1 = data1;
    let number2 = data2;

    let sum = number1+number2;

    return sum;
}

function subtraction(digit1, digit2){
    let number1 = digit1;
    let number2 = digit2;

    let sub = number1-number2;

    return sub;
}

let sumResult = summation(40, 20); //60
console.log(sumResult);


console.log(summation(45, 54));

console.log(subtraction(20, 23)); //-3

